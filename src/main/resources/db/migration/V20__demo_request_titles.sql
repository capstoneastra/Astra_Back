UPDATE test_requests q
SET title = m.new_title
FROM (VALUES
        ('진동시험 의뢰서 작성 중',      '소형 위성 구조물 진동시험'),
        ('전장품 진동시험 접수 대기',    '위성 전원 모듈 진동시험'),
        ('위성 전장품 진동시험 검토 중', '위성 전장품 발사 환경 진동시험'),
        ('추가 정보 입력 대기',          '탑재체 브래킷 진동시험'),
        ('추가 정보 제출 완료',          '탑재체 구조 시편 진동시험'),
        ('시험 일정 조율 중',            '드론 프레임 진동 내구시험'),
        ('시험 일정 확정',               '큐브위성 부품 진동시험'),
        ('진동시험 완료 · 성적서 발행',  '발사체 전장 박스 진동시험'),
        ('시료 규격 초과로 반려',        '대형 구조물 진동시험')
     ) AS m(old_title, new_title)
WHERE q.title = m.old_title
  AND q.requester_id IN (SELECT id FROM users WHERE email = 'company@astra.kr');
