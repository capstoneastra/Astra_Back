--  * 예전 스크립트는 "시험 일정 확정", "추가 정보 입력 대기"처럼 상태를 설명하는 제목을 붙여
--    의뢰 목록에서 제목과 상태가 같은 말을 반복해 보였음 → 시험 이름으로 바꿈
--  * company@astra.kr 이 낸 의뢰 중 제목이 정확히 같은 것만 바꿈 (없으면 아무것도 안 함)
